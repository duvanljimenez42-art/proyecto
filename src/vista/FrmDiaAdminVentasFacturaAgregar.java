    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        //int id = Integer.parseInt(this.txtId.getText());
        String numero_factura = this.txtNumero_factura.getText();
        String fecha_hora = this.txtFecha_hora.getText();
        String metodo_pago = this.txtMetodo_pago.getText();
        float costo_servicio_adicional = Integer.parseInt(this.txtCosto_servicio_adicional.getText());
        float subtotal = Integer.parseInt(this.txtSubtotal.getText());
        float iva_total = Integer.parseInt(this.txtIva_total.getText());
        float total = Integer.parseInt(this.txtTotal.getText());
        int empleados_id = Integer.parseInt(this.txtEmpleados_id.getText());
        int clientes_id = Integer.parseInt(this.txtClientes_id.getText());

        this.objVentasFactura.setNumero_factura(numero_factura);
        this.objVentasFactura.setFecha_hora(fecha_hora);
        this.objVentasFactura.setMetodo_pago(metodo_pago);
        this.objVentasFactura.setCosto_servicio_adicional(costo_servicio_adicional);
        this.objVentasFactura.setSubtotal(subtotal);
        this.objVentasFactura.setIva_total(iva_total);
        this.objVentasFactura.setTotal(total);
        this.objVentasFactura.setEmpleados_id(empleados_id);
        this.objVentasFactura.setClientes_id(clientes_id);

        this.dispose();
    }//GEN-LAST:event_btnAceptarActionPerformed

