        this.objClientes.setEmail(email);
        this.objClientes.setNombre_comercial(nombre_comercial);
        this.objClientes.setContacto_autorizado(contacto_autorizado);
        this.objClientes.setTipoCliente_id(tipoCliente_id);

        this.dispose();
